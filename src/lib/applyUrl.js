// ลิงก์สมัครเรียน
//
// เป็นลิงก์ระดับมหาวิทยาลัย ไม่ได้แยกตามหลักสูตร — ตรวจจากหน้าเว็บคณะ
// (https://sci.pnru.ac.th/programs.php) เมื่อ 27 ต.ค. 2569 ว่ายังเป็นที่อยู่เดียวกัน
//
// เคยเขียนตายตัวซ้ำสองที่ในแถบเมนู ย้ายมาไว้ที่นี่เพราะถ้ามหาวิทยาลัยย้ายหน้า
// การแก้สองแห่งจะลืมแห่งหนึ่งเสมอ
export const APPLY_URL = 'https://admission.pnru.ac.th/info/announce'

/**
 * ลิงก์สมัครของหลักสูตรหนึ่ง
 *
 * ถ้าวันหนึ่งหลักสูตรใดมีช่องทางรับสมัครของตัวเอง ผู้ดูแลกรอก apply_url ไว้ใน
 * ข้อมูลหลักสูตรได้ แล้วหน้ารายละเอียดจะใช้ค่านั้นแทนลิงก์กลาง
 *
 * ระบบนี้ไม่รับสมัครเองและไม่เก็บข้อมูลผู้สมัคร — ส่งต่อไปที่ของมหาวิทยาลัยเท่านั้น
 */
export const applyUrlFor = (detail) => {
  const own = typeof detail?.apply_url === 'string' ? detail.apply_url.trim() : ''
  return own || APPLY_URL
}
