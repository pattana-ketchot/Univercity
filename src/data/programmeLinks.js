// ถ้าคำตอบอ้างเอกสารของหลักสูตรเหล่านี้ จะได้เฉพาะปุ่มเอกสารกับปุ่มเว็บไซต์คณะ

const BY_SOURCE_TITLE = new Map(
  PROGRAMMES.flatMap((p) => p.sourceTitles.map((title) => [title, p]))
)

/**
 * หาสาขาจากชื่อหลักสูตรที่หลังบ้านส่งมาใน X-Source-Programme
 *
 * เทียบตรงทุกตัวอักษร (ตัดช่องว่างหัวท้ายให้เท่านั้น) ไม่เจอคืน null
 * ผู้เรียกต้องไม่แสดงปุ่มสาขาเมื่อได้ null ห้ามเดาต่อ
 */
export function resolveProgramme(sourceProgramme) {
  if (typeof sourceProgramme !== 'string') return null
  return BY_SOURCE_TITLE.get(sourceProgramme.trim()) || null
}
